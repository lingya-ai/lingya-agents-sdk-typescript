// Generates the channel-bound public facade from the canonical operation manifest.
//
// OpenAPI Generator must retain channelId because it is part of the HTTP path. The
// public SDK removes only parameters marked as client-bound, then injects their
// values after the caller has selected a channel and external user.

import { readFile, writeFile } from 'node:fs/promises';

const manifest = JSON.parse(await readFile(new URL('../openapi/endpoints.json', import.meta.url), 'utf8'));
const output = new URL('../src/bound.ts', import.meta.url);
const upperFirst = (value) => `${value[0].toUpperCase()}${value.slice(1)}`;
const lowerFirst = (value) => `${value[0].toLowerCase()}${value.slice(1)}`;
const apiClass = (group) => group === 'sql' ? 'SQLApi' : `${upperFirst(group)}Api`;
const generatedApiClass = (group) => `Generated${apiClass(group)}`;
const requestType = (operationId) => `${upperFirst(operationId)}Request`;
const parameterProperty = (name) => {
    if (name === 'X-Request-ID') return 'xRequestID';
    if (name === 'Accept') return 'accept';
    return name;
};
const bodyProperty = (schema) => {
    if (schema === 'ReturnedReferenceList') return 'returnedReference';
    return schema ? lowerFirst(schema) : null;
};
const pathParameters = (operation) => operation.parameters.filter((parameter) => parameter.in === 'path' && !parameter.boundFrom);
const optionParameters = (operation) => operation.parameters.filter((parameter) => parameter.in !== 'path' && !parameter.boundFrom);
const optionType = (operation) => `${upperFirst(operation.operationId)}Options`;
const groups = [...new Set(manifest.map((operation) => operation.group))];

const requestTypes = manifest.map((operation) => requestType(operation.operationId));
const lines = [
    '// This file is generated by scripts/generate-bound-api.mjs. Do not edit it manually.',
    '//',
    '// These facades bind channelId once so application code cannot accidentally sign a',
    '// request for a channel that differs from the client configuration.',
    '',
    `import { ${[...groups.map((group) => `${apiClass(group)} as ${generatedApiClass(group)}`), ...requestTypes.map((name) => `type ${name}`)].join(', ')} } from './apis';`,
    "import { ChatStreamProbeEventFromJSON, type ChatStreamProbeEvent } from './models/ChatStreamProbeEvent';",
    "import { decodeAiChatBriefEvent, type AiChatBriefEvent } from './events';",
    "import { decodeSse } from './sse';",
    '',
    'type BoundRawRequest = (method: string, suffix: string, bodyJson: string | undefined, query: URLSearchParams | undefined, accept: string, requestId?: string) => Promise<Response>;',
    '',
];

for (const operation of manifest) {
    const optionParams = optionParameters(operation);
    if (optionParams.length === 0) continue;
    const omitted = [
        'channelId',
        ...pathParameters(operation).map((parameter) => parameterProperty(parameter.name)),
        ...(operation.requestBodySchema ? [bodyProperty(operation.requestBodySchema)] : []),
    ];
    lines.push('/** Query values and optional request headers that are not bound by the client. */');
    lines.push(`export type ${optionType(operation)} = Omit<${requestType(operation.operationId)}, ${omitted.map((name) => `'${name}'`).join(' | ')}>;`);
    lines.push('');
}

lines.push('/** Generated APIs retained as an explicit compatibility escape hatch until 1.0. */');
lines.push('export class AgentsLowLevelApis {');
for (const group of groups) lines.push(`    public readonly ${group}: ${generatedApiClass(group)};`);
lines.push('');
lines.push(`    public constructor(${groups.map((group) => `${group}: ${generatedApiClass(group)}`).join(', ')}) {`);
for (const group of groups) lines.push(`        this.${group} = ${group};`);
lines.push('    }');
lines.push('}');
lines.push('');

for (const group of groups) {
    const className = `${upperFirst(group)}Api`;
    const delegateClass = generatedApiClass(group);
    const operations = manifest.filter((operation) => operation.group === group);
    lines.push(`/** Channel-bound ${group} operations for one external user. */`);
    lines.push(`export class ${className} {`);
    lines.push('    public constructor(');
    lines.push('        private readonly channelId: string,');
    lines.push(`        private readonly delegate: ${delegateClass},`);
    if (operations.some((operation) => operation.sse)) lines.push('        private readonly rawRequest: BoundRawRequest,');
    lines.push('    ) {}');
    lines.push('');

    for (const operation of operations) {
        const request = requestType(operation.operationId);
        const paths = pathParameters(operation);
        const options = optionParameters(operation);
        const inputSchema = operation.requestBodySchema;
        const parameters = paths.map((parameter) => `${parameterProperty(parameter.name)}: ${request}['${parameterProperty(parameter.name)}']`);
        if (inputSchema) parameters.push(`input: ${request}['${bodyProperty(inputSchema)}']`);
        if (options.length > 0) {
            const hasRequired = options.some((parameter) => parameter.required);
            parameters.push(`options: ${optionType(operation)}${hasRequired ? '' : ' = {}'}`);
        }
        const isBinary = operation.response.format === 'binary' || operation.response.mediaType === 'text/csv';
        const returnType = operation.sse
            ? operation.operationId === 'streamChatEvents' ? 'AsyncGenerator<AiChatBriefEvent>' : 'AsyncGenerator<ChatStreamProbeEvent>'
            : isBinary ? 'Promise<Uint8Array>' : `ReturnType<${delegateClass}['${operation.operationId}']>`;
        lines.push('    /**');
        lines.push(`     * ${operation.summary}`);
        lines.push('     *');
        for (const parameter of paths) lines.push(`     * @param ${parameterProperty(parameter.name)} - ${parameter.description}`);
        if (inputSchema) lines.push(`     * @param input - ${operation.summary} 的强类型请求体。 / Typed request body for ${operation.operationId}.`);
        if (options.length > 0) lines.push('     * @param options - 查询参数与可选请求头。 / Query parameters and optional request headers.');
        lines.push(`     * @returns ${operation.sse ? '可取消的强类型事件序列。 / A cancellable typed event sequence.' : '契约定义的强类型响应。 / The typed response defined by the contract.'}`);
        lines.push('     */');
        lines.push(`    public ${operation.sse ? 'async *' : isBinary ? 'async ' : ''}${operation.operationId}(${parameters.join(', ')}): ${returnType} {`);
        const requestFields = ['channelId: this.channelId', ...paths.map((parameter) => parameterProperty(parameter.name))];
        if (inputSchema) requestFields.push(`${bodyProperty(inputSchema)}: input`);
        if (options.length > 0) requestFields.push('...options');
        if (operation.sse) {
            let suffix = operation.relativePath;
            for (const parameter of paths) suffix = suffix.replace(`{${parameter.name}}`, `\${encodeURIComponent(String(${parameterProperty(parameter.name)}))}`);
            lines.push(`        const suffix = \`${suffix}\`;`);
            lines.push(`        const response = await this.rawRequest('${operation.method}', suffix, JSON.stringify(input), undefined, 'text/event-stream', options?.xRequestID);`);
            lines.push('        for await (const data of decodeSse(response)) {');
            if (operation.operationId === 'streamChatEvents') lines.push('            yield decodeAiChatBriefEvent(data);');
            else lines.push('            yield ChatStreamProbeEventFromJSON(JSON.parse(data));');
            lines.push('        }');
        } else if (isBinary) {
            lines.push(`        const value = await this.delegate.${operation.operationId}({ ${requestFields.join(', ')} });`);
            lines.push('        return new Uint8Array(await value.arrayBuffer());');
        } else {
            lines.push(`        return this.delegate.${operation.operationId}({ ${requestFields.join(', ')} });`);
        }
        lines.push('    }');
        lines.push('');
    }
    lines.push('}');
    lines.push('');
}

lines.push('/** @deprecated Use AgentsLowLevelApis. */');
lines.push('export { AgentsLowLevelApis as LingyaAgentsLowLevelApis };');
for (const group of groups) {
    const currentName = `${upperFirst(group)}Api`;
    lines.push(`/** @deprecated Use ${currentName}. */`);
    lines.push(`export { ${currentName} as Lingya${upperFirst(group)}Api };`);
}
lines.push('');

await writeFile(output, `${lines.join('\n').trimEnd()}\n`, 'utf8');
